// packs/retreat/manifest.ts
// Исполняемый манифест курса «Ретрит с двух сторон»: ядро академии + доменные правила
// про обещания денег, группы, юридической защиты и исцеления. Курс говорит о деньгах
// честно и вслух («курс не обещает дохода», «это не юридическая консультация») —
// поэтому правила сужены до ОБЕЩАЮЩИХ конструкций (закреплено в manifest.test.ts рядом).
// RU-паттерны без \b — JS \b не работает вокруг кириллицы (см. lib/authoring/dehustle.ts).
import type { ManifestRule } from '../../lib/authoring/manifest'
import { CORE_MANIFEST } from '../../lib/authoring/manifest'

export const MANIFEST: ManifestRule[] = [
  ...CORE_MANIFEST,
  {
    // «не обещает дохода» и «посчитай, сколько ты заработаешь» не матчатся — только гарантия.
    pattern: 'гарантированн(ый|о|ого) (доход|заработ|прибыл)|гарантированно заработа|guaranteed (income|profit|earnings)|(earn|profit) guaranteed',
    label: 'обещание денег: гарантированный доход',
  },
  {
    pattern: 'наполним (вашу |твою )?группу|группа наберётся гарантированно|соберём (вам |тебе )?группу|we will fill your (retreat|group)|guaranteed sell-?out|sold out guaranteed',
    label: 'обещание группы: «наполним группу»',
  },
  {
    // «это не юридическая консультация» не матчится.
    pattern: 'юридически безопас|защитит (вас |тебя )?от суда|защищает от суда|legally bulletproof|protects you from (any )?lawsuits?',
    label: 'обещание юридической защиты',
  },
  {
    // «практика не лечит и не исцеляет» не матчится: ловим только утверждение исцеления.
    pattern: '(практика|ретрит|программа) (исцеляет|исцелит|вылечит)|(practice|retreat|program) (heals|will heal|cures)',
    label: 'обещание исцеления в описании практики',
  },
]
