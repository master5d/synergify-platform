// Исполняемый манифест курса «Тишина, в которой слышно»: ядро академии + доменные
// правила про обещания практики. Курс честно говорит «не гарантирует», «не заменяет
// терапию», «сверхспособностей НЕТ» — поэтому правила сужены до ОБЕЩАЮЩИХ конструкций
// и не должны падать на легитимных отрицаниях (закреплено в manifest.test.ts рядом).
// RU-паттерны без \b — JS \b не работает вокруг кириллицы (см. lib/authoring/dehustle.ts).
import type { ManifestRule } from '../../lib/authoring/manifest'
import { CORE_MANIFEST } from '../../lib/authoring/manifest'

export const MANIFEST: ManifestRule[] = [
  ...CORE_MANIFEST,
  {
    // «гарантирует»/«не гарантирует» НЕ матчится — только 1-е лицо и «гарантированн-».
    pattern: 'гарантируем|гарантирую|гарантированн|we guarantee',
    label: 'обещание практики: гарантия от первого лица',
  },
  {
    pattern: 'исцелит|вылечит|will (heal|cure)',
    label: 'обещание практики: «исцелит/вылечит» (медицинское обещание)',
  },
  {
    // EN тоже только обещающие конструкции: «a substitute for psychotherapy»
    // легитимно живёт в словаре в списке «чего здесь НЕТ».
    pattern: 'заменит (психо)?терапи|(will|can) replace (psycho)?therapy|replaces (psycho)?therapy',
    label: 'обещание практики: «заменит (психо)терапию»',
  },
  {
    // Слово «сверхспособности» легитимно в списках «чего НЕТ» — матчим только
    // обещающие конструкции «обретёшь/получишь/разовьёшь сверхспособности».
    pattern: '(обрет[её]шь|обретёте|обретете|получишь|получите|разовь[её]шь|разовьёте|разовьете|да[её]т|дадут) сверхспособност|(gain|unlock|develop|grants?) superpowers',
    label: 'обещание практики: сверхспособности как результат',
  },
]
